from __future__ import annotations

from datetime import datetime
from typing import Any


def generate_report(eval_result: dict[str, Any]) -> str:
    metrics = eval_result.get("metrics", {})
    ts = eval_result.get("timestamp", datetime.now().isoformat())

    lines = []
    lines.append("# Search Evaluation Report")
    lines.append(f"Generated: {ts}")
    lines.append(f"Total queries: {eval_result.get('total_queries', 0)}")
    lines.append(f"Top-K: {eval_result.get('top_k', 10)}")
    lines.append("")

    lines.append("## Summary Metrics")
    lines.append("")
    lines.append("| Metric | Score |")
    lines.append("|--------|-------|")

    sorted_metrics = sorted(metrics.items(), key=lambda x: x[0])
    for name, score in sorted_metrics:
        if isinstance(score, float):
            lines.append(f"| {name} | {score:.4f} |")
        elif isinstance(score, dict):
            lines.append(f"| {name} | (see breakdown) |")
        else:
            lines.append(f"| {name} | {score} |")

    lines.append("")

    per_query = eval_result.get("per_query", {})
    lines.append("## Per-Query Breakdown")
    lines.append("")
    for q, data in sorted(per_query.items()):
        result_ids = data.get("result_ids", data.get("retrieved", []))
        expected = data.get("expected", [])
        hits = sum(1 for r in result_ids if r in expected)
        lines.append(f"- **{q}**: retrieved={len(result_ids)}, expected={len(expected)}, hits={hits}")
        if "intent" in data and data["intent"]:
            lines.append(f"  - intent: {data['intent']}")
        if result_ids:
            found = [r for r in result_ids if r in expected]
            if found:
                lines.append(f"  - found: {', '.join(found[:5])}")

    lines.append("")
    lines.append("---")
    lines.append(f"_Report generated by framework-search v1.0_")

    return "\n".join(lines)


def generate_comparison_report(comparison: dict[str, Any]) -> str:
    delta = comparison.get("delta", {})
    baseline_metrics = comparison.get("baseline_metrics", {})
    candidate_metrics = comparison.get("candidate_metrics", {})
    ranking_diff = comparison.get("ranking_diff", {})
    metrics_report = comparison.get("metrics_report", {})

    lines = []
    lines.append("# Search Evaluation Comparison Report")
    lines.append(f"Generated: {comparison.get('timestamp', datetime.now().isoformat())}")
    lines.append("")

    lines.append("## Metric Deltas")
    lines.append("")
    lines.append("| Metric | Baseline | Candidate | Delta |")
    lines.append("|--------|----------|-----------|-------|")

    all_metrics = sorted(set(baseline_metrics) | set(candidate_metrics))
    for m in all_metrics:
        base = baseline_metrics.get(m, 0.0)
        cand = candidate_metrics.get(m, 0.0)
        d = delta.get(m, 0.0)
        base_str = f"{base:.4f}" if isinstance(base, float) else str(base)
        cand_str = f"{cand:.4f}" if isinstance(cand, float) else str(cand)
        d_str = f"{d:+.4f}" if isinstance(d, float) else str(d)
        lines.append(f"| {m} | {base_str} | {cand_str} | {d_str} |")

    lines.append("")
    lines.append("## Ranking Stability")
    lines.append("")
    lines.append(f"- Total queries: {ranking_diff.get('total_queries', 0)}")
    lines.append(f"- Improved: {ranking_diff.get('improved', 0)}")
    lines.append(f"- Worsened: {ranking_diff.get('worsened', 0)}")
    lines.append(f"- Unchanged: {ranking_diff.get('unchanged', 0)}")
    lines.append(f"- Average overlap: {ranking_diff.get('avg_overlap', 0):.4f}")

    if metrics_report:
        lines.append("")
        lines.append("## Metrics Report")
        lines.append("")
        lines.append(f"- RSI: {metrics_report.get('ranking_stability_index', 0):.4f}")
        lines.append(f"- Top-1 unchanged rate: {metrics_report.get('top_1_unchanged_rate', 0):.4f}")
        lines.append(f"- Top-3 Jaccard: {metrics_report.get('top_3_jaccard', 0):.4f}")
        lines.append(f"- Top-10 Jaccard: {metrics_report.get('top_10_jaccard', 0):.4f}")
        lines.append(f"- Changed queries: {metrics_report.get('changed_queries', 0)}")
        lines.append(f"- Improved queries: {metrics_report.get('improved', 0)}")
        lines.append(f"- Regressed queries: {metrics_report.get('regressed', 0)}")
        lines.append(f"- Largest rank movement: {metrics_report.get('largest_rank_movement', 0)}")

    lines.append("")
    lines.append("---")
    lines.append(f"_Comparison report generated by framework-search v1.0_")

    return "\n".join(lines)
